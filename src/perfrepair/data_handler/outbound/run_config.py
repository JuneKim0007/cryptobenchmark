from __future__ import annotations

from pathlib import Path

import yaml

GENERATED_NAME = "generated_perf_repair.yaml"
BASE_GLOBAL = Path("config/global.yaml")
ALL_TEST_SET = Path("config/testsets/all.yaml")
KEPT_SECTIONS = ("run", "policy")


def _merge(base: dict, overrides: dict) -> dict:
    """One level deep, matching how the benchmark merges `harness`."""
    merged = dict(base)
    for key, value in overrides.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = {**merged[key], **value}
        else:
            merged[key] = value
    return merged


def build_run_config(base: dict, test_set: Path, run_overrides: dict | None = None) -> dict:
    # Absolute: the benchmark resolves a relative testSet against the global file's directory, not ours.
    doc = {"schemaVersion": base.get("schemaVersion", 1),
           "selection": {"testSet": str(Path(test_set).resolve()), "exclude": []}}
    for section in KEPT_SECTIONS:
        if section in base:
            doc[section] = base[section]
    if run_overrides:
        doc["run"] = _merge(doc.get("run") or {}, run_overrides)
    return doc


def write_run_config(out_dir: Path, benchmark: Path, base: Path | None = None,
                     run_overrides: dict | None = None, test_set: Path | None = None) -> Path:
    benchmark = Path(benchmark).resolve()
    base = Path(base).resolve() if base else benchmark / BASE_GLOBAL
    test_set = Path(test_set).resolve() if test_set else benchmark / ALL_TEST_SET
    for required in (base, test_set):
        if not required.is_file():
            raise FileNotFoundError(f"missing_file: {required}")
    doc = build_run_config(yaml.safe_load(base.read_text()) or {}, test_set, run_overrides)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / GENERATED_NAME
    header = (f"# generated by perf-repair from {base}; edits are overwritten on the next run\n"
              f"# selection: every primitive {test_set.name} selects, nothing excluded\n")
    out.write_text(header + yaml.safe_dump(doc, sort_keys=False, default_flow_style=None))
    return out
