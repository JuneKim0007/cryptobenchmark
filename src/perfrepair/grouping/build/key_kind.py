"""A service's key kind from recorded fields only: ordered rules, the first that answers wins.

1. measured: the kind preparation used for the service (prepared.yaml), when the catalog allows it
2. engine type: the catalog lists one key kind for the type
3. key generator: the key algorithm the trial used is generated by a KeyGenerator (secret) or a
   KeyPairGenerator (pair) registered on the device
4. key formats / key classes the provider declares
5. unknown
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

from ..catalog.families import Families

SECRET, PAIR, UNKNOWN = "secret", "pair", "unknown"


@dataclass(frozen=True)
class Evidence:
    engine_type: str
    measured_kind: str | None
    key_algorithm: str | None
    key_formats: tuple[str, ...]
    key_classes: tuple[str, ...]


@dataclass(frozen=True)
class Context:
    families: Families
    secret_generators: frozenset[str]   # upper-cased names and aliases of KeyGenerator services
    pair_generators: frozenset[str]     # the same for KeyPairGenerator


Rule = Callable[[Evidence, Context], str | None]


def _known(ctx: Context, engine_type: str) -> list[str]:
    return [k for k in ctx.families.key_kinds(engine_type) if k != UNKNOWN]


def measured(e: Evidence, ctx: Context) -> str | None:
    return e.measured_kind if e.measured_kind in _known(ctx, e.engine_type) else None


def engine_type(e: Evidence, ctx: Context) -> str | None:
    kinds = _known(ctx, e.engine_type)
    return kinds[0] if len(kinds) == 1 else None


def key_generator(e: Evidence, ctx: Context) -> str | None:
    if not e.key_algorithm:
        return None
    name = e.key_algorithm.upper()
    if name in ctx.secret_generators:
        return SECRET
    if name in ctx.pair_generators:
        return PAIR
    return None


def declared(e: Evidence, ctx: Context) -> str | None:
    formats = {f.upper() for f in e.key_formats}
    if "RAW" in formats:
        return SECRET
    if formats & {"PKCS#8", "X.509"}:
        return PAIR
    classes = " ".join(e.key_classes)
    if "SecretKey" in classes:
        return SECRET
    if "PrivateKey" in classes or "PublicKey" in classes:
        return PAIR
    return None


RULES: tuple[tuple[str, Rule], ...] = (("measured", measured), ("engine_type", engine_type),
                                       ("key_generator", key_generator), ("declared", declared))


def key_kind(e: Evidence, ctx: Context) -> tuple[str, str]:
    """(key kind, the rule that decided it); the kind is one the catalog lists for the engine type."""
    for name, rule in RULES:
        kind = rule(e, ctx)
        if kind is not None and kind in ctx.families.key_kinds(e.engine_type):
            return kind, name
    return UNKNOWN, "none"
