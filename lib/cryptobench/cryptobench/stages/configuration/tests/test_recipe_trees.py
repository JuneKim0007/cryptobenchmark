"""tests/contracts/catalogue/recipe-trees.yaml: every recipe a catalogue entry's required rows name, at the base entry and each build, as guide_items.parameter_tree makes it; Kotlin's document Recipes reads the same cases."""
import os

import yaml

from cryptobench.shared import paths
from cryptobench.shared.catalogue.algorithms import algorithms
from cryptobench.shared.catalogue.guide_items import parameter_tree
from cryptobench.shared.catalogue.recipes import load
from cryptobench.shared.catalogue.views import view_for

FIXTURE = paths.repo().contract_catalogue / "recipe-trees.yaml"
HEADER = "# Generated by test_recipe_trees.py (UPDATE_GOLDEN=1): the tree each recipe an entry's rows name makes at a build, or the refusal code.\n"


def cases() -> list[dict]:
    recipes = load().by_id
    found = []
    for entry in sorted(algorithms().entries, key=lambda e: e.id):
        for build in [None, *sorted((entry.raw.get("providers") or {}).keys())]:
            required = (view_for(entry.id, build) if build else view_for(entry.id)).get("required") or []
            rows = {r["name"]: r for r in required}
            for recipe in sorted({r["recipe"] for r in required if r.get("recipe")}):
                case = {"id": entry.id, "build": build, "recipe": recipe}
                try:
                    case["tree"] = parameter_tree(recipe, rows, recipes)
                except LookupError:
                    case["refused"] = "guide_recipe_unbuildable"
                found.append(case)
    return found


def test_the_fixture_holds_every_recipe_row_as_parameter_tree_makes_it():
    found = {"schemaVersion": 1, "cases": cases()}
    if os.environ.get("UPDATE_GOLDEN"):
        FIXTURE.write_text(HEADER + yaml.safe_dump(found, sort_keys=False, width=200))
    assert yaml.safe_load(FIXTURE.read_text()) == found
