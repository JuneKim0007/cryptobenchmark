"""One suite's composition: the target's config and overlays as layers, selection.testSet the suite, written in the session folder, never in results."""
from __future__ import annotations

from pathlib import Path

from cryptobench.shared.document.dump import FLOW_LEAVES, dump_yaml
from cryptobench.shared.document.write import write_text

SCHEMA_VERSION = 1   # GlobalDocument.schemaVersion


def written(config: Path, overlays: tuple[Path, ...], suite: Path, path: Path) -> Path:
    document = {"schemaVersion": SCHEMA_VERSION, "layers": [str(layer) for layer in (config, *overlays)], "selection": {"testSet": str(suite)}}
    header = f"# generated by the session for suite {suite}; edits are overwritten\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    return write_text(path, header + dump_yaml(document, FLOW_LEAVES))
