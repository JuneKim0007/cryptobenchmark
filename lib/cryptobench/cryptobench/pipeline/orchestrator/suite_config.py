"""One suite's global.yaml: the target's config with selection.testSet set to the suite, written in the session folder, never in results."""
from __future__ import annotations

from pathlib import Path

from cryptobench.shared.document.document import read_yaml
from cryptobench.shared.document.dump import FLOW_LEAVES, dump_yaml
from cryptobench.shared.document.write import write_text


def written(config: Path, suite: Path, path: Path) -> Path:
    document = read_yaml(config)
    selection = {**(document.get("selection") or {}), "testSet": str(suite)}
    header = f"# generated by the session from {config} for suite {suite}; edits are overwritten\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    return write_text(path, header + dump_yaml({**document, "selection": selection}, FLOW_LEAVES))
