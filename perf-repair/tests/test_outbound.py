import json
import shutil
from pathlib import Path

import pytest
import yaml

from perfrepair.data_handler.outbound import (GENERATED_NAME, BenchmarkRunError, benchmark_root, new_run_dir,
                                              run_pipeline, write_run_config)

FAKE = Path(__file__).parent / "fixtures" / "outbound" / "fake_pipeline.py"

BASE = """schemaVersion: 1
selection:
  testSet: testsets/scope.yaml
  exclude: [{provider: Slow}]
run:
  inputSizes: [64, 1024]
  processRepetitions: 1
  harness: {iterations: 50, profiling: none}
policy:
  onFailure: skip
"""


@pytest.fixture
def bench_root(tmp_path):
    root = tmp_path / "bench"
    (root / "scripts").mkdir(parents=True)
    shutil.copy(FAKE, root / "scripts" / "pipeline.py")
    (root / "config" / "testsets").mkdir(parents=True)
    (root / "config" / "global.yaml").write_text(BASE)
    (root / "config" / "testsets" / "all.yaml").write_text("schemaVersion: 1\nconfig:\n")
    return root


def test_selects_everything_and_keeps_run_and_policy(bench_root, tmp_path):
    out = write_run_config(tmp_path / "run", bench_root)
    doc = yaml.safe_load(out.read_text())
    assert out.name == GENERATED_NAME
    assert doc["selection"] == {"testSet": str((bench_root / "config/testsets/all.yaml").resolve()), "exclude": []}
    assert Path(doc["selection"]["testSet"]).is_absolute()
    assert doc["run"]["inputSizes"] == [64, 1024]
    assert doc["policy"] == {"onFailure": "skip"}
    assert doc["schemaVersion"] == 1


def test_header_names_the_generator_and_base(bench_root, tmp_path):
    first = (write_run_config(tmp_path, bench_root)).read_text().splitlines()[0]
    assert first.startswith("# generated by perf-repair from ")
    assert str((bench_root / "config/global.yaml").resolve()) in first


def test_run_overrides_merge_harness_field_by_field(bench_root, tmp_path):
    out = write_run_config(tmp_path, bench_root,
                           run_overrides={"processRepetitions": 3, "harness": {"iterations": 5}})
    run = yaml.safe_load(out.read_text())["run"]
    assert run["processRepetitions"] == 3
    assert run["harness"] == {"iterations": 5, "profiling": "none"}
    assert run["inputSizes"] == [64, 1024]


def test_explicit_base_and_missing_files(bench_root, tmp_path):
    base = tmp_path / "other.yaml"
    base.write_text("schemaVersion: 1\nselection: {testSet: x.yaml}\npolicy: {onFailure: stop}\n")
    doc = yaml.safe_load(write_run_config(tmp_path / "r", bench_root, base=base).read_text())
    assert doc["policy"] == {"onFailure": "stop"} and "run" not in doc
    with pytest.raises(FileNotFoundError, match="missing_file"):
        write_run_config(tmp_path / "r", bench_root, base=tmp_path / "absent.yaml")


def test_new_run_dir_never_reuses(tmp_path):
    a, b = new_run_dir(tmp_path / "runs"), new_run_dir(tmp_path / "runs")
    assert a != b and a.is_dir() and b.is_dir() and a.parent == b.parent
    assert a.name.endswith("Z") or "Z-" in a.name


@pytest.mark.parametrize("stage,flag", [("configure", None), ("bench", "--bench"), ("device", "--device")])
def test_runner_passes_stage_and_returns_manifest(bench_root, tmp_path, stage, flag):
    config = write_run_config(tmp_path, bench_root)
    seen = []
    manifest = run_pipeline(config, tmp_path / "benchmark", stage, bench_root, echo=seen.append)
    assert manifest == (tmp_path / "benchmark" / "manifest.yaml").resolve()
    argv = json.loads((tmp_path / "benchmark" / "argv.json").read_text())["argv"]
    assert argv[argv.index("--config") + 1] == str(config.resolve())
    assert ("--bench" in argv, "--device" in argv) == (flag == "--bench", flag == "--device")
    assert seen[0] == "line 0" and (tmp_path / "benchmark" / "pipeline.log").is_file()


def test_runner_failure_carries_the_tail(bench_root, tmp_path, monkeypatch):
    monkeypatch.setenv("FAKE_EXIT", "3")
    with pytest.raises(BenchmarkRunError) as e:
        run_pipeline(tmp_path / "c.yaml", tmp_path / "out", benchmark=bench_root, echo=None, tail=5)
    message = str(e.value)
    assert "exited 3" in message and "error: fake failure" in message
    assert "line 0" not in message


def test_runner_fails_when_no_manifest(bench_root, tmp_path, monkeypatch):
    monkeypatch.setenv("FAKE_NO_MANIFEST", "1")
    with pytest.raises(BenchmarkRunError, match="wrote no"):
        run_pipeline(tmp_path / "c.yaml", tmp_path / "out", benchmark=bench_root, echo=None)


def test_benchmark_root_lookup(bench_root, tmp_path, monkeypatch):
    monkeypatch.setenv("CRYPTOBENCH_ROOT", str(bench_root))
    assert benchmark_root() == bench_root.resolve()
    with pytest.raises(BenchmarkRunError, match="CRYPTOBENCH_ROOT"):
        benchmark_root(tmp_path / "nowhere")
    with pytest.raises(ValueError):
        run_pipeline(tmp_path / "c.yaml", tmp_path / "out", "measure", bench_root)
