"""The global.yaml a delta measures with: the stored benchmark's own config, its run block untouched, its test set's
include replaced by the gap items and their anchors, overrides kept so every case is planned as before."""
from __future__ import annotations

from pathlib import Path

import yaml

from ..dto.grouping import parse_qualified
from ..files import read_yaml, write_text_making_parents
from ..stop.halt import Coded

DELTA = "delta"
GLOBAL, TEST_SET = "global.yaml", "testset.yaml"


def rules(items) -> list[dict]:
    """One include per item in the provider's declared spelling, as the probe registers it."""
    return [dict(zip(("type", "name", "provider"), parse_qualified(i))) for i in sorted(items)]


def _test_set(config: Path, document: dict) -> Path:
    named = (document.get("selection") or {}).get("testSet")
    path = Path(named) if named and Path(named).is_absolute() else Path(config).parent / (named or "")
    if not named or not path.is_file():
        raise Coded(f"delta_unconfigured: {config} names test set {named!r}, not a file; a delta plans with the stored test set")
    return path


def write_delta_config(stored: Path, folder: Path, items) -> Path:
    """stored: the config the benchmark ran with (manifest config); written under <folder>/delta/."""
    if not Path(stored).is_file():
        raise Coded(f"delta_unconfigured: {stored}, the stored benchmark's config, is gone; a delta measures with it")
    document = read_yaml(stored) or {}
    test_set = read_yaml(_test_set(stored, document)) or {}
    out = Path(folder) / DELTA
    planned = write_text_making_parents(out / TEST_SET, "# generated by perf-repair: the benchmark gate's delta\n"
                                        + yaml.safe_dump({**test_set, "include": rules(items)}, sort_keys=False))
    selection = {"testSet": str(planned.resolve()), "exclude": []}
    return write_text_making_parents(out / GLOBAL, f"# generated by perf-repair from {stored}: the benchmark gate's delta\n"
                                     + yaml.safe_dump({**document, "selection": selection}, sort_keys=False))


def write_rerun_config(stored: Path, folder: Path, items) -> Path:
    """device.benchmark.onSetupMismatch rerun: the stored config whole, the gap items added to its test set, none excluded."""
    document = read_yaml(stored) or {}
    test_set = read_yaml(_test_set(stored, document)) or {}
    added = [r for r in rules(items) if r not in (test_set.get("include") or [])]
    out = Path(folder) / DELTA
    planned = write_text_making_parents(out / f"rerun-{TEST_SET}", "# generated by perf-repair: a whole rerun\n" + yaml.safe_dump(
        {**test_set, "include": (test_set.get("include") or []) + added} if test_set.get("include") else test_set,
        sort_keys=False))
    kept = [r for r in (document.get("selection") or {}).get("exclude") or [] if r not in rules(items)]
    selection = {"testSet": str(planned.resolve()), "exclude": kept}
    return write_text_making_parents(out / f"rerun-{GLOBAL}", f"# generated by perf-repair from {stored}: a whole rerun\n"
                                     + yaml.safe_dump({**document, "selection": selection}, sort_keys=False))
