"""The benchmark's selection with device.filterByApps: what the last run measured, what the used set still lacks, and the
global.yaml that measures only a set: the base file with every other device item added to `selection.exclude`."""
from __future__ import annotations

from pathlib import Path

import yaml

from cryptobench.paths import RunTree
from ..dto.device import DeviceRecord
from cryptobench.catalogue.grouping import Item
from ..dto.screen import Verdict
from ..dto.used import names_digest
from ..files import read_yaml, write_text
from .selection_adds import write_test_set

FILTER_OFF = "device.filterByApps off: the last benchmark measured the apps' items only"
UNKNOWN = "device.yaml records no used-set benchmark, the manifest is not the base global.yaml's"


def measured(record: DeviceRecord | None) -> frozenset[str] | None:
    """None: the base selection whole, so nothing a used set needs is missing."""
    return frozenset(record.benchmark["items"]) if record and record.benchmark else None


def lacking(record: DeviceRecord | None, manifest_config: str | None, base_config: str) -> str | None:
    """Why the benchmark reruns for the used set: only when no used-set benchmark is recorded; a set that grew is the
    benchmark gate's to measure in a delta (device/gate.py), so a used-set change alone reruns nothing."""
    return None if measured(record) is not None or manifest_config == base_config else UNKNOWN


def _canonical(item: Item, verdict: Verdict | None) -> tuple:
    name = verdict.canonical if verdict and verdict.canonical else item.name
    return item.provider, item.type, name, verdict.keySize if verdict else None


def algorithm_of(item: Item, verdict: Verdict | None) -> tuple:
    return _canonical(item, verdict)[1:]


def bundled_named(items: list[Item], verdicts: dict[int, Verdict] | None, harness: frozenset[str],
                  sites: list[Item]) -> frozenset[str]:
    """A harness-bundled provider's items a site names the algorithm of; its others are a dependency no site asks about."""
    v = verdicts or {}
    named = {algorithm_of(i, v.get(i.id)) for i in sites}
    return frozenset(i.qualified for i in items if i.provider in harness and algorithm_of(i, v.get(i.id)) in named)


def exclusions(items: list[Item], verdicts: dict[int, Verdict] | None, keep: frozenset[str]) -> list[dict]:
    """An exclude rule matches every spelling of a canonical name, so one a kept item shares is never excluded."""
    kept = {_canonical(i, (verdicts or {}).get(i.id)) for i in items if i.qualified in keep}
    return [{"provider": i.provider, "type": i.type, "name": i.name} for i in items
            if i.qualified not in keep and _canonical(i, (verdicts or {}).get(i.id)) not in kept]


def relocated(base: Path) -> dict:
    """The base global.yaml as a file in the device folder reads it: a relative test set resolved against the base."""
    document = read_yaml(base) or {}
    selection = dict(document.get("selection") or {})
    if selection.get("testSet"):
        selection["testSet"] = str((Path(base).parent / selection["testSet"]).resolve())
    return {**document, "selection": selection}


def generated(path: Path, base: Path, why: str, document: dict) -> Path:
    write_text(path, f"# generated by perf-repair from {base}: {why}; edits are overwritten\n"
               + yaml.safe_dump(document, sort_keys=False, default_flow_style=None))
    return path


def write_config(base: Path, folder: Path, rules: list[dict], adds: list[dict] = ()) -> Path:
    """adds: include rules the test set gains, written as its own copy (device/selection_adds.py)."""
    document = relocated(base)
    selection = {**document["selection"], "exclude": list(document["selection"].get("exclude") or []) + rules}
    if adds and selection.get("testSet"):
        selection["testSet"] = str(write_test_set(Path(selection["testSet"]), folder, list(adds)))
    return generated(RunTree(folder).used_config, base, "device.filterByApps", {**document, "selection": selection})


def section(manifest_config: str, keep: frozenset[str]) -> dict:
    return {"config": manifest_config, "used": names_digest(keep), "items": sorted(keep)}
