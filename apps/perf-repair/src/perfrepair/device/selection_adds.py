"""The used set's additions to the test set: an include rule per used item the base test set may not plan, in the
provider's declared spelling, written as a test set beside the device folder; config/testsets stays as authored."""
from __future__ import annotations

from pathlib import Path

import yaml

from cryptobench.paths import RunTree
from ..data_handler.inbound import read_manifest
from ..data_handler.inbound.manifest import manifest_file
from cryptobench.catalogue.grouping import Item, qualified
from ..files import read_yaml, write_text


def not_runnable(folder: Path) -> frozenset[str]:
    """The inventory's items the trial could not run: an include of one would only add a skip."""
    path = RunTree(folder).manifest
    if not path.is_file():
        return frozenset()
    manifest, base = read_manifest(path)
    inventory = manifest_file(manifest, base, "inventory")
    providers = (read_yaml(inventory).get("providers") or {}) if inventory else {}
    return frozenset(qualified(t, a, p) for p, types in providers.items() for t, algorithms in (types or {}).items()
                     for a, v in (algorithms or {}).items() if isinstance(v, dict) and v.get("runs") is False)


def includes(items: list[Item], keep: frozenset[str], refused: frozenset[str]) -> list[dict]:
    return [{"provider": i.provider, "type": i.type, "name": i.name} for i in items
            if i.qualified in keep and i.qualified not in refused]


def write_test_set(test_set: Path, folder: Path, rules: list[dict]) -> Path:
    """The base test set with the rules added to its include; an empty include already plans the whole inventory."""
    # a missing test set is the pipeline's to refuse, with its own coded line
    document = (read_yaml(test_set) or {}) if Path(test_set).is_file() else {}
    if not document.get("include") or not rules:
        return Path(test_set)
    added = [r for r in rules if r not in document["include"]]
    out = RunTree(folder).used_test_set
    write_text(out, f"# generated by perf-repair from {test_set}: device.filterByApps adds every used item; edits are "
               "overwritten\n" + yaml.safe_dump({**document, "include": document["include"] + added}, sort_keys=False,
                                                 default_flow_style=None))
    return out
